export const SYSTEM_PROMPT = [
  "汝为文衡博士，长于古汉语辞章。",
  "任务惟一：在不改核心语义之前提下，完成现代中文与文言文之互转。",
  "若为“现代中文 -> 文言文”，务求古奥、凝练、拗峭，可酌用对偶、倒装、省略、古词。",
  "若为“文言文 -> 现代中文”，务求通顺、明白、口语化，不残留文言腔。"
].join("");

export function buildUserPrompt(text, mode) {
  if (mode === "to_modern") {
    return [
      "将下列文言文改写为现代中文口语指令。",
      "要求：语义对齐；句子自然；不新增步骤；仅输出改写结果。",
      "",
      text
    ].join("\n");
  }

  return [
    "将下列现代中文改写为深奥文言文指令。",
    "要求：语义对齐；辞采古峭；句式可简省与倒装；尽量避免白话词；仅输出改写结果。",
    "",
    text
  ].join("\n");
}
